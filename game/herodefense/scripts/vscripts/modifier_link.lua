-- 链接所有可能出现的苦难修饰器
function InitModifierLink()
    local challengeList = KeyValues.challenge_info
    for key, value in pairs(challengeList) do
        for i = 1, 5, 1 do
            local keyName = "level"..i
            if value[keyName] and  value[keyName]>=1 then
                local modifier_name = "modifier_"..key.."_"..i
                -- print("modifier_name=",modifier_name)
                local file_index = 1
                if value.file then
                    file_index = value.file
                    -- print("第二文件")
                    -- print("link.."..modifier_name)
                end


                LinkLuaModifier(modifier_name, "modifier/modifier_challenge"..file_index, LUA_MODIFIER_MOTION_NONE)
                modifier_name = modifier_name.."_show"
                -- print("modifier_name=",modifier_name)
                LinkLuaModifier(modifier_name, "modifier/modifier_challenge_show", LUA_MODIFIER_MOTION_NONE)
                -- ChallengeInfo_001_1
            end
        end
    end


    local potionList = KeyValues.game_shop_chaotic_era_potion
    -- 链接药剂modifier
    for item, value in pairs(potionList) do
        if value.weight then
            -- 没权重的不要
            local name = "modifier/chaotic_era_potion/modifier_"..item
            print("name=",name)
            LinkLuaModifier("modifier_"..item, "modifier/chaotic_era_potion/modifier_"..item, LUA_MODIFIER_MOTION_NONE)
        end

    end

    local chaotic_era_creep_buff = KeyValues.chatic_era_creep_buff
    for buffName, value in pairs(chaotic_era_creep_buff) do
        -- local name = "modifier/chaotic_era_creep_buff/"..buffName
        LinkLuaModifier(buffName, "modifier/chaotic_era_creep_buff/"..buffName, LUA_MODIFIER_MOTION_NONE)

    end


    local map_effect = KeyValues.map_effect
    for item, value in pairs(map_effect) do
        if value.weight then
            -- 没权重的不要
            -- local name = "modifier/chaotic_era_buff_card/modifier_"..item
            LinkLuaModifier("modifier_"..item, "modifier/chaotic_era_buff_card/modifier_"..item, LUA_MODIFIER_MOTION_NONE)
        end

    end

    local artifact = KeyValues.artifact
    for item, value in pairs(artifact) do
        if value.weight then
            LinkLuaModifier("modifier_"..item, "modifier/chaotic_era_artifact/modifier_"..item, LUA_MODIFIER_MOTION_NONE)
        end

    end
end



